const description = document.querySelector('meta[name="description"]');
const languageButtons = document.querySelectorAll("[data-language]");

const syncCaptionTracks = (language) => {
  document.querySelectorAll("video").forEach((video) => {
    video.querySelectorAll('track[kind="captions"]').forEach((track) => {
      const trackLanguage = track.getAttribute("srclang") || track.srclang;
      const isSelected = trackLanguage === language;
      track.default = isSelected;

      if (track.track) {
        track.track.mode = isSelected ? "showing" : "disabled";
      }
    });
  });
};

const setLanguage = (language) => {
  const messages = translations[language];
  if (!messages) {
    return;
  }

  document.documentElement.lang = language;
  document.title = messages.title;
  description?.setAttribute("content", messages.description);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key && messages[key]) {
      element.textContent = messages[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (key && messages[key]) {
      element.setAttribute("aria-label", messages[key]);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (key && messages[key]) {
      element.setAttribute("alt", messages[key]);
    }
  });

  languageButtons.forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });

  syncCaptionTracks(language);
};

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.language);
  });
});

if (typeof module !== "undefined") {
  module.exports = { setLanguage, syncCaptionTracks, translations };
}
